    private void searchButtonMouseClicked(java.awt.event.MouseEvent evt) {//GEN-FIRST:event_searchButtonMouseClicked
        
        if(Long.parseLong(minPriceField.getValue().toString()) > Long.parseLong(maxPriceField.getValue().toString()))
        {
            minPriceField.setValue(0);
            maxPriceField.setValue(1000000000);
        }
        
        List<Ad> ads = new ArrayList();
        List<String> lines = new ArrayList<>();
        adsf.clear();
        
        laptopSpecs.setText("");
        laptopsList.removeAllItems();
        
        if(Files.exists(path, LinkOption.NOFOLLOW_LINKS))
        {
            try {
                lines = Files.readAllLines(path, Charset.forName("UTF-8"));
            } catch (IOException ex) {
                Logger.getLogger(NewApplication.class.getName()).log(Level.SEVERE, null, ex);
            }
            Gson gson = new Gson();
            lines.forEach(line -> ads.add(gson.fromJson(line, Ad.class)));

            adsf = ads.stream().filter(ad -> 
                    ad.getLaptop().getBrand().contains(brandField1.getSelectedItem().toString().trim()) &&
                    ad.getLaptop().getModel().toLowerCase().contains(modelField1.getText().toLowerCase().trim()) &&
                    ad.getPrice() >= Long.parseLong(minPriceField.getValue().toString()) &&
                    ad.getPrice() <= Long.parseLong(maxPriceField.getValue().toString()) &&
                    ad.getLaptop().getScreen().getTech().contains(screenTechField1.getSelectedItem().toString().trim()) &&
                    ad.getLaptop().getScreen().getRes().contains(screenResField1.getSelectedItem().toString().trim()) &&
                    ad.getLaptop().getCpu().getBrand().contains(cpuBrandField1.getSelectedItem().toString().trim()) &&
                    ad.getLaptop().getCpu().getModel().toLowerCase().contains(cpuModelField1.getText().toLowerCase().trim()) &&
                    ad.getLaptop().getGpu().getBrand().contains(gpuBrandField1.getSelectedItem().toString().trim()) &&
                    ad.getLaptop().getGpu().getModel().toLowerCase().contains(gpuModelField1.getText().toLowerCase().trim()) &&
                    ad.getLaptop().getRam().getGen().contains(ramGenField1.getSelectedItem().toString().trim()) &&
                    ad.getLaptop().getDisk().getHdd().contains(hddField1.getSelectedItem().toString().trim()) &&
                    ad.getLaptop().getDisk().getSsd().contains(ssdField1.getSelectedItem().toString().trim())
                                    ).collect(Collectors.toList());
            
            int cpuCores = Integer.parseInt(cpuCoresField1.getValue().toString());
            int gpuMemory = Integer.parseInt(gpuMemoryField1.getValue().toString());
            int ramMemory = Integer.parseInt(ramMemoryField1.getValue().toString());
            String screenSize = screenSizeField1.getSelectedItem().toString().trim();
            if(!screenSize.equals("") || cpuCores != 0 || gpuMemory != 0 || ramMemory != 0)
            {
                if(!screenSize.equals(""))
                {
                    adsf = adsf.stream().filter(ad -> ad.getLaptop().getScreen().getSize() == Float.parseFloat(screenSize)).collect(Collectors.toList());
                }
                if(cpuCores != 0)
                {
                    adsf = adsf.stream().filter(ad -> ad.getLaptop().getCpu().getCores() == cpuCores).collect(Collectors.toList());
                }
                if(gpuMemory != 0)
                {
                    adsf = adsf.stream().filter(ad -> ad.getLaptop().getGpu().getMemory() == gpuMemory).collect(Collectors.toList());
                }
                if(ramMemory != 0)
                {
                    adsf = adsf.stream().filter(ad -> ad.getLaptop().getRam().getMemory() == ramMemory).collect(Collectors.toList());
                }
            }
            ArrayList<String> list = new ArrayList<>();
            adsf.forEach(ad -> list.add(ad.getTitle() + " - " + ad.getPrice()));
            list.forEach(ad -> laptopsList.addItem(ad));
        }
    }//GEN-LAST:event_searchButtonMouseClicked

