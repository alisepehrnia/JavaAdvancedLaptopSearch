    private void acceptButtonMouseClicked(java.awt.event.MouseEvent evt) {//GEN-FIRST:event_acceptButtonMouseClicked
        // TODO add your handling code here:
        if(modelField.getText().isEmpty())
            JOptionPane.showMessageDialog(null, "عنوان آگهی نباید خالی باشد");
        if(cpuModelField.getText().isEmpty())
            JOptionPane.showMessageDialog(null, "سری و مدل CPU را وارد کنید");
        if(gpuModelField.getText().isEmpty())
            JOptionPane.showMessageDialog(null, "مدل کارت گرافیک را وارد کنید");
        if(!modelField.getText().isEmpty() && !cpuModelField.getText().isEmpty() && !gpuModelField.getText().isEmpty())
        {
            Core.Screen screen = new Core.Screen();
            screen.setSize(Float.parseFloat(screenSizeField.getSelectedItem().toString()));
            screen.setTech(screenTechField.getSelectedItem().toString());
            screen.setRes(screenResField.getSelectedItem().toString());
            screen.setIsTouch(isTouch.isSelected());
            
            Core.CPU cpu = new Core.CPU(cpuBrandField.getSelectedItem().toString(), Integer.parseInt(cpuCoresField.getValue().toString()), cpuModelField.getText());
            
            Core.GPU gpu = new Core.GPU(gpuBrandField.getSelectedItem().toString(), Integer.parseInt(gpuMemoryField.getValue().toString()), gpuModelField.getText());
            
            Core.RAM ram = new Core.RAM();
            ram.setMemory(Integer.parseInt(ramMemoryField.getValue().toString()));
            ram.setGen(Integer.parseInt(ramGenField.getSelectedItem().toString()));
            ram.setFreq(Integer.parseInt(ramFreqField.getSelectedItem().toString()));
            
            Core.Disk disk = new Core.Disk(Integer.parseInt(hddField.getSelectedItem().toString()), Integer.parseInt(ssdField.getSelectedItem().toString()));
            
            Core.Peripherals periphs = new Core.Peripherals();
            periphs.setUsb2(Integer.parseInt(usb2Field.getValue().toString()));
            periphs.setUsb3(Integer.parseInt(usb3Field.getValue().toString()));
            periphs.setHaveWireless(haveWireless.isSelected());
            periphs.setHaveLan(haveLan.isSelected());
            periphs.setHaveBluetooth(haveBluetooth.isSelected());
            periphs.setHaveVga(haveVga.isSelected());
            periphs.setHaveHdmi(haveHdmi.isSelected());
            
            Core.Laptop laptop = new Core.Laptop(brandField.getSelectedItem().toString(), modelField.getText(), screen, cpu, gpu, ram, disk, periphs);
            
            Core.Ad ad = new Core.Ad(laptop.getBrand() + " " + laptop.getModel(), phoneField.getText(), regionField.getText(), laptop);
            
            Gson gson = new Gson();
            String output = gson.toJson(ad);
            
            JOptionPane.showMessageDialog(null, output);
            
            JOptionPane.showMessageDialog(null, "آگهی با موفقیت ثبت شد!");
        }
    }//GEN-LAST:event_acceptButtonMouseClicked

